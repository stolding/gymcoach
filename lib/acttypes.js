// naam uit Apple Health → { type (categorie), label (Nederlandse naam) }
export function classify(name) {
  let n = String(name || '').trim();
  const raw = /^other\s+(\d+)$/i.exec(n);
  if (raw && RAW[raw[1]]) n = RAW[raw[1]];
  const low = n.toLowerCase();
  const hit = LIST.find(([re]) => re.test(low));
  if (hit) return { type: hit[2], label: hit[1] };
  return { type: 'overig', label: n && !/^other(\s+\d+)?$/i.test(n) ? n : 'Overige activiteit' };
}
